#Requires -Version 5.1
# Generates THIRD_PARTY_LICENSES.md for every Go module actually linked into the
# coordinated gomobile runtime (waruntime + igruntime + liruntime + msgruntime).
# Re-run after any go.mod change. Fails (exit 1) if a module has no detectable license.
param([string]$Out = "")
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$repo = Resolve-Path (Join-Path $root "..\..")
$env:GOROOT = Join-Path $repo "tmp\go126root\go"
$env:GOPATH = Join-Path $repo "tmp\gopath"
$go = Join-Path $env:GOROOT "bin\go.exe"
if (-not $Out) { $Out = Join-Path $root "THIRD_PARTY_LICENSES.md" }
$packages = @("./waruntime", "./igruntime", "./liruntime", "./msgruntime")

# Upstream repos that ship code without a LICENSE file; license confirmed from source headers.
$overrides = @{
  "github.com/beeper/poly1305" = "BSD-3-Clause (fork of golang.org/x/crypto; per-file Go Authors headers, repo has no LICENSE file)"
}

function Classify([string]$text) {
  if ($text -match 'AFFERO') { return 'AGPL-3.0' }
  if ($text -match 'GNU LESSER') { return 'LGPL' }
  if ($text -match 'GNU GENERAL PUBLIC LICENSE') { return 'GPL-3.0' }
  if ($text -match 'Mozilla Public License') { return 'MPL-2.0' }
  if ($text -match 'Apache License') { return 'Apache-2.0' }
  if ($text -match 'Redistribution and use in source and binary forms') {
    if ($text -match 'Neither the name|names of its') { return 'BSD-3-Clause' } else { return 'BSD-2-Clause' }
  }
  if ($text -match 'Permission is hereby granted') { return 'MIT' }
  if ($text -match 'Permission to use, copy, modify, and(/or)? distribute') { return 'ISC' }
  return 'UNKNOWN'
}

Push-Location $root
try {
  $mods = & $go list -deps -f '{{if .Module}}{{.Module.Path}}{{end}}' @packages | Sort-Object -Unique
  $perPkg = @{}
  foreach ($p in $packages) {
    $perPkg[$p] = & $go list -deps -f '{{if .Module}}{{.Module.Path}}{{end}}' $p | Sort-Object -Unique
  }
  $rows = foreach ($m in $mods) {
    if ($m -eq 'app.mini.hub/whatsappRuntime') { continue }
    $j = & $go list -m -json $m | ConvertFrom-Json
    $dir = if ($j.Replace) { $j.Replace.Dir } else { $j.Dir }
    $ver = if ($j.Replace) { "$($j.Replace.Path)@$($j.Replace.Version)" } else { $j.Version }
    $lic = Get-ChildItem $dir -File | Where-Object { $_.Name -match '^(LICEN[SC]E|COPYING)' } | Select-Object -First 1
    $kind = if ($overrides.ContainsKey($m)) { $overrides[$m] } elseif ($lic) { Classify ((Get-Content $lic.FullName -TotalCount 40) -join ' ') } else { 'UNKNOWN' }
    $hash = if ($lic) { (Get-FileHash $lic.FullName -Algorithm SHA256).Hash.Substring(0, 16) } else { '-' }
    $used = ($packages | Where-Object { $perPkg[$_] -contains $m } | ForEach-Object { $_.TrimStart('./') }) -join ', '
    [pscustomobject]@{ Module = $m; Version = $ver; License = $kind; Hash = $hash; UsedBy = $used }
  }
} finally { Pop-Location }

$lines = @(
  "# Third-party licenses: MINI phone-local runtime (libgojni.so)",
  "",
  "Generated by ``license-inventory.ps1``. Do not edit by hand.",
  "Scope: every Go module linked into ``waruntime``, ``igruntime``, ``liruntime``, ``msgruntime``.",
  "``Hash`` = first 16 hex chars of the SHA-256 of the module's license file.",
  "",
  "| Module | Version | License | Hash | Linked by |",
  "|---|---|---|---|---|"
)
foreach ($r in ($rows | Sort-Object License, Module)) {
  $lines += "| $($r.Module) | $($r.Version) | $($r.License) | $($r.Hash) | $($r.UsedBy) |"
}
$copyleft = $rows | Where-Object { $_.License -match 'GPL' }
$lines += ""
$lines += "## Strong copyleft modules"
$lines += ""
foreach ($c in $copyleft) { $lines += "- $($c.Module) ($($c.License)), linked by: $($c.UsedBy)" }
$lines -join "`n" | Set-Content -Path $Out -Encoding utf8
Write-Host "Wrote $Out ($($rows.Count) modules)"
$unknown = $rows | Where-Object { $_.License -eq 'UNKNOWN' }
if ($unknown) { $unknown | ForEach-Object { Write-Host "UNKNOWN license: $($_.Module)" }; exit 1 }
